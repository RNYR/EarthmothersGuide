"""Write Media/logo.svg: the guide's in-game arrow inside a ring that is open at the top, so the
arrow points out through the gap. The panel's own colours (UI.lua COLORS), clean vector art.
Usage: python3 -I tools/make_logo.py Media/logo.svg
       rsvg-convert -w 1024 -h 1024 Media/logo.svg -o Media/logo-1024.png   (and -w 400 -h 400)
"""
import math, sys

CX, CY = 512, 512
BG = '#291c12'      # dark hide brown (panel background)
WHEAT = '#d9b77a'   # panel title colour
GREEN = '#6fd64a'   # the arrow when you are on course
DARK = '#0e0a06'    # the arrow's outline

# The arrowhead exactly as tools/make_arrow.py draws it (0..1 texture coordinates).
HEAD = [(0.50, 0.08), (0.90, 0.88), (0.50, 0.68), (0.10, 0.88)]
OUTLINE = 0.028
SIZE = 430

RING_R, RING_W = 360, 24
GAP = 35            # the ring stops this many degrees either side of north


def f(v):
    return f'{v:.1f}'


cy0 = (HEAD[0][1] + HEAD[1][1] + HEAD[2][1]) / 3
arrow = ' '.join(f'{f(CX + (u - 0.5) * SIZE)},{f(CY + (v - cy0) * SIZE)}' for u, v in HEAD)


def on_ring(deg):
    t = math.radians(deg)
    return CX + RING_R * math.sin(t), CY - RING_R * math.cos(t)


(x0, y0), (x1, y1) = on_ring(GAP), on_ring(360 - GAP)

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">
  <!-- Earthmother's Guide logo. Original artwork (C) 2026 Vard Ruun, GPL-3.0-only.
       Generated by tools/make_logo.py - edit that, not this file. -->
  <rect width="1024" height="1024" fill="{BG}"/>
  <path d="M {f(x0)} {f(y0)} A {RING_R} {RING_R} 0 1 1 {f(x1)} {f(y1)}" fill="none" stroke="{WHEAT}"
        stroke-width="{RING_W}" stroke-linecap="round"/>
  <polygon points="{arrow}" fill="{GREEN}" stroke="{DARK}" stroke-width="{f(OUTLINE * SIZE * 2)}"
           stroke-linejoin="miter" stroke-miterlimit="10" paint-order="stroke"/>
</svg>
'''
with open(sys.argv[1], 'w', encoding='utf-8') as fh:
    fh.write(svg)
print('wrote', sys.argv[1])
